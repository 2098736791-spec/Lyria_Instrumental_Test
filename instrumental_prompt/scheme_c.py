def strip_wrappers(text: str) -> str:
    """剥掉模型偶尔加的代码块围栏或首尾引号。"""
    t = text.strip()
    if t.startswith("```"):
        first_nl = t.find("\n")
        if first_nl != -1:
            t = t[first_nl + 1:]
        if t.rstrip().endswith("```"):
            t = t.rstrip()[:-3]
    for q in ('"', "'", "「", "」", "“", "”"):
        t = t.strip(q)
    return t.strip()
